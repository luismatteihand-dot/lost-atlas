        ok('pas d\'invitation plein écran hors iPhone', await pg.evaluate("Immersion.canInstall()") == False)
        await ctx.close()
        # iPhone Safari, hors écran d'accueil
        ctx, pg = await fresh(ua=IPHONE, intro=False)
        await pg.click('[data-act="intro-go"]'); await pg.wait_for_timeout(1400)
