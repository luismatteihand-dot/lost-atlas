import asyncio, json, subprocess, time, sys
from playwright.async_api import async_playwright
srv = subprocess.Popen([sys.executable, '-m', 'http.server', '8765', '--directory', 'lost-atlas'], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
time.sleep(1)
async def main():
    errs = []
    async with async_playwright() as p:
        b = await p.chromium.launch(channel='chrome', args=['--no-sandbox'])
        ctx = await b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, is_mobile=True, has_touch=True,
                                  geolocation={'latitude': 31.62590, 'longitude': -7.98940, 'accuracy': 12}, permissions=['geolocation'], service_workers='block')
        pg = await ctx.new_page()
        pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' and 'tile.openstreetmap' not in m.text and 'ERR_' not in m.text else None)
        pg.on('pageerror', lambda e: errs.append('PAGEERROR ' + str(e)))
        await pg.goto('http://localhost:8765/index.html'); await pg.wait_for_timeout(1500)
        await pg.screenshot(path='s1.png')
        await pg.click('[data-act="intro-go"]'); await pg.wait_for_timeout(1200)
        await pg.add_style_tag(content='#cardfx{display:none!important}')
        print('noTiles', await pg.evaluate('AtlasMap.noTiles()'), 'markers', await pg.locator('.mk').count())
        await pg.screenshot(path='s2.png')
        # lieu : validation manuelle hors GPS (lieu éloigné)
        await pg.evaluate("UI.openPlace('t3-01')"); await pg.click('[data-act="here"]'); await pg.wait_for_timeout(1500)
        print('msg:', (await pg.locator('.manual p').inner_text())[:90])
        await pg.click('[data-act="here-manual"]'); await pg.wait_for_timeout(400)
        print('status t3-01', await pg.evaluate("Game.status('t3-01')"))
        await pg.click('[data-act="obs-go"]'); await pg.wait_for_timeout(200)
        await pg.click('[data-act="en-hint"]')
        await pg.click('[data-act="en-reveal"]'); await pg.wait_for_timeout(300)
        print('status t3-01', await pg.evaluate("Game.status('t3-01')"), 'codex', await pg.evaluate("Object.keys(Game.S.codex)"))
        await pg.screenshot(path='s3.png')
        await pg.fill('textarea.notes', 'Cour superbe'); await pg.dispatch_event('textarea.notes', 'change')
        # GPS : suivi -> découverte automatique de la place
        await pg.click('[data-act="sheet-close"] >> nth=1'); await pg.click('#fab-gps'); await pg.wait_for_timeout(2500); print('avant de révéler', await pg.evaluate("Game.status('t1-x-place')"), '| radar', await pg.locator('#radar').inner_text()); await pg.evaluate("document.querySelector('#radar').click()"); await pg.click('[data-act="here"]'); await pg.wait_for_timeout(600); await pg.click('#sh-close')
        print('place', await pg.evaluate("Game.status('t1-x-place')"), 'how', await pg.evaluate("Game.pget('t1-x-place').how"), 'radar', await pg.locator('#radar').inner_text())
        await pg.wait_for_timeout(3200); await pg.screenshot(path='s4.png')
        # marqueur perso
        await pg.click('#fab-pin'); await pg.click('[data-act="pick-ok"]'); await pg.click('[data-act="pin-icon"][data-v="?"]'); await pg.click('#sh-close')
        # territoire + liste
        await pg.click('.tchip >> nth=0'); await pg.wait_for_timeout(300); print('rows', await pg.locator('.row[data-name]').count())
        await pg.click('[data-act="terr-tab"][data-tab="pratique"]'); await pg.fill('.search', 'café'); print('filtrés', await pg.locator('.row[data-name]:visible').count())
        await pg.click('.row[data-name]:visible >> nth=0'); await pg.click('[data-act="sheet-back"]'); await pg.click('#sh-close')
        # quêtes : classement + secret
        await pg.click('#tabbar [data-v="quetes"]'); await pg.click('[data-act="open-quest"][data-id="q-nom"]')
        for i, k in enumerate(['fait', 'hyp', 'trad', 'fait']): await pg.click(f'[data-act="cl-pick"][data-i="{i}"][data-k="{k}"]')
        await pg.click('[data-act="cl-check"]'); await pg.wait_for_timeout(300); print('q-nom', await pg.evaluate("Game.questStatus(Data.Q['q-nom'])"))
        await pg.click('#sh-close'); await pg.click('[data-act="open-quest"][data-id="q-derb"]'); await pg.click('[data-act="quest-hint"]'); await pg.click('[data-act="cf-ok"]')
        await pg.screenshot(path='s5.png'); await pg.click('#sh-close')
        # codex + chaîne (forcée) 
        await pg.evaluate("UI.show('codex')"); await pg.click('#v-codex [data-act="open-codex"] >> nth=1'); await pg.wait_for_timeout(200); await pg.screenshot(path='s6.png'); await pg.click('#sh-close')
        await pg.evaluate("['t1-x-koutoubia','t4-01','t4-02'].forEach(i=>Game.discover(i,'manuel'));UI.after()")
        await pg.click('[data-act="codex-tab"][data-v="chaines"]'); await pg.click('[data-act="open-chain"][data-id="s-dynasties"]')
        for i in range(6): await pg.click(f'[data-act="chain-add"][data-i="{i}"]')
        await pg.click('[data-act="chain-check"]'); await pg.wait_for_timeout(300); print('chain', await pg.evaluate("Game.chainDone('s-dynasties')")); await pg.click('#sh-close')
        await pg.click('#tabbar [data-v="collection"]'); await pg.click('[data-act="sac-tab"][data-v="objets"]'); await pg.click('.art.got >> nth=0'); await pg.click('#sh-close')
        await pg.click('#tabbar [data-v="profil"]'); await pg.wait_for_timeout(4000); await pg.screenshot(path='s7.png', full_page=False)
        await pg.click('[data-act="open-export"]'); n = len(await pg.input_value('#export-txt')); print('export chars', n); await pg.click('#sh-close')
        xp = await pg.evaluate('Game.totalXP()')
        await pg.reload(); await pg.wait_for_timeout(1200)
        print('persist', xp == await pg.evaluate('Game.totalXP()'), xp, 'lvl', await pg.evaluate('Game.level()'), 'intro shown again:', await pg.locator('.intro-sheet').count())
        print('overflowX', await pg.evaluate('document.documentElement.scrollWidth > innerWidth'))
        await b.close()
    print('ERRORS:', errs)
try: asyncio.run(main())
finally: srv.terminate()
