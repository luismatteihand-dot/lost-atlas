import asyncio, subprocess, time, sys, json
from playwright.async_api import async_playwright
srv = subprocess.Popen([sys.executable, '-m', 'http.server', '8797', '--directory', 'lost-atlas'], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); time.sleep(1)
URL = 'http://localhost:8797/index.html'; R = []
def ok(name, cond, extra=''):
    R.append(bool(cond)); print(('OK   ' if cond else 'FAIL ') + name + (' — ' + str(extra) if extra != '' else ''))
IPHONE = 'Mozilla/5.0 (iPhone; CPU iPhone OS 18_1 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/18.1 Mobile/15E148 Safari/604.1'
async def main():
    errs = []
    async with async_playwright() as p:
        b = await p.chromium.launch(channel='chrome', args=['--no-sandbox', '--autoplay-policy=no-user-gesture-required'])
        async def fresh(geo=(31.65, -7.96), ua=None, intro=True):
            kw = dict(viewport={'width': 390, 'height': 844}, device_scale_factor=2, is_mobile=True, has_touch=True, service_workers='block', geolocation={'latitude': geo[0], 'longitude': geo[1], 'accuracy': 10}, permissions=['geolocation'])
            if ua: kw['user_agent'] = ua
            ctx = await b.new_context(**kw); pg = await ctx.new_page()
            pg.on('pageerror', lambda e: errs.append('PAGEERROR ' + str(e)))
            pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' and 'tile.openstreetmap' not in m.text and 'ERR_' not in m.text else None)
            await pg.goto(URL); await pg.wait_for_timeout(1300)
            if intro: await pg.click('[data-act="intro-go"]'); await pg.wait_for_timeout(300)
            await pg.add_style_tag(content='#cardfx{display:none!important}')
            return ctx, pg
        ctx, pg = await fresh()
        d = await pg.evaluate("(() => { const L = Quotidien.list(); return { n: L.length, ids: new Set(L.map(p => p.id)).size, terr: L.every(p => Data.T[p.t]), src: L.every(p => p.src && p.q === 'osm' && p.ll.length === 2), clash: L.filter(p => Data.P[p.id]).length, fams: Quotidien.families().length }; })()")
        ok('900 lieux du quotidien chargés, identifiants uniques', d['n'] >= 800 and d['ids'] == d['n'], d)
        ok('chaque lieu a un territoire, une source et un niveau de fiabilité', d['terr'] and d['src'])
        ok('aucun identifiant ne recouvre un lieu de l\'atlas (sauvegardes intactes)', d['clash'] == 0 and await pg.evaluate("Data.places.length") == 186)
        # carte : rien en vue d'ensemble, regroupement au zoom moyen, pastilles au zoom fort
        lm = "AtlasMap.leaflet()"
        await pg.evaluate(f"{lm}.setView([31.6258, -7.9891], 13)"); await pg.wait_for_timeout(400)
        n13 = await pg.locator('.qm, .qc').count()
        await pg.evaluate(f"{lm}.setView([31.6258, -7.9891], 16)"); await pg.wait_for_timeout(400)
        c16, s16 = await pg.locator('.qc').count(), await pg.locator('.qm').count()
        await pg.evaluate(f"{lm}.setView([31.6258, -7.9891], 18)"); await pg.wait_for_timeout(400)
        c18, s18 = await pg.locator('.qc').count(), await pg.locator('.qm').count()
        ok('vue d\'ensemble : la ville reste lisible (aucun point du quotidien)', n13 == 0, n13)
        ok('zoom moyen : les points serrés se regroupent, sans masquer la carte', c16 > 0 and c16 + s16 < 80, (c16, s16))
        ok('zoom fort : chaque lieu a sa pastille', c18 == 0 and s18 > 0, (c18, s18))
        await pg.screenshot(path='q-carte18.png')
        await pg.evaluate(f"{lm}.setView([31.6258, -7.9891], 16)"); await pg.wait_for_timeout(400)
        await pg.screenshot(path='q-carte16.png')
        await pg.locator('.qc').first.click(); await pg.wait_for_timeout(500)
        ok('toucher un regroupement zoome dessus', await pg.evaluate(f"{lm}.getZoom()") > 16)
        # filtres
        await pg.evaluate(f"{lm}.setView([31.6258, -7.9891], 18)"); await pg.wait_for_timeout(300)
        before = await pg.locator('.qm').count()
        await pg.click('#fab-layers'); await pg.wait_for_timeout(300)
        ok('calques : familles filtrables, pratiques et lieux de culte masqués par défaut', await pg.locator('[data-act="quot-fam"]').count() == 13 and await pg.locator('[data-act="quot-fam"][data-k="utile"].on').count() == 0 and await pg.locator('[data-act="quot-fam"][data-k="cafe"].on').count() == 1)
        await pg.screenshot(path='q-calques.png')
        await pg.click('[data-act="quot-fam"][data-k="resto"]'); await pg.wait_for_timeout(300)
        after = await pg.evaluate("document.querySelectorAll('.qm').length")
        ok('masquer les restaurants retire leurs pastilles', after < before, (before, after))
        await pg.click('[data-act="quot-terr"][data-id="t2"]'); await pg.wait_for_timeout(500)
        ok('filtre territoire : seul Mouassine reste sur la carte', await pg.evaluate("Object.values(AtlasMap.leaflet()._layers).length > 0") and await pg.evaluate("Game.S.settings.layers.terr") == 't2')
        await pg.evaluate("UI.closeSheet()"); await pg.click('#fab-layers'); await pg.click('[data-act="quot-terr"][data-id=""]'); await pg.click('[data-act="quot-fam"][data-k="resto"]'); await pg.evaluate("UI.closeSheet()")
        # fiche et découverte
        cafe = await pg.evaluate("Quotidien.list().find(p => p.f === 'cafe' && p.t === 't1').id")
        await pg.evaluate(f"Quotidien.open('{cafe}')"); await pg.wait_for_timeout(300)
        txt = await pg.locator('#sheet').inner_text()
        ok('fiche : nom, catégorie, territoire, statut, position, source', all(k.lower() in txt.lower() for k in ('Café', 'Inconnu', 'OpenStreetMap', 'non vérifiés', 'Place Jemaa')), txt[:200].replace('\n', ' | '))
        ok('fiche : aucune description inventée', 'n\'en donne pas' in txt)
        await pg.screenshot(path='q-fiche.png')
        await pg.evaluate("AtlasMap.simulate(31.70, -7.90, 10)"); await pg.wait_for_timeout(200)
        await pg.click('[data-act="quot-here"]'); await pg.wait_for_timeout(200)
        ok('« J\'y suis » loin du lieu avec GPS : refusé, distance donnée', not await pg.evaluate(f"Quotidien.found('{cafe}')"))
        ll = await pg.evaluate(f"Quotidien.get('{cafe}').ll")
        await pg.evaluate(f"AtlasMap.simulate({ll[0] + 0.0001}, {ll[1]}, 10)"); await pg.wait_for_timeout(200)
        xp0 = await pg.evaluate("Game.totalXP()")
        await pg.evaluate(f"Quotidien.open('{cafe}')"); await pg.click('[data-act="quot-here"]'); await pg.wait_for_timeout(300)
        ok('sur place : visité par GPS, petite récompense (+5), pas de carte', await pg.evaluate(f"Quotidien.found('{cafe}')") and await pg.evaluate("Game.totalXP()") - xp0 == 5 and not await pg.evaluate("V3.st().cards['c-habitue']"))
        ids = await pg.evaluate("Quotidien.list().filter(p => p.f === 'cafe').slice(0, 6).map(p => p.id)")
        await pg.evaluate(f"{json.dumps(ids)}.forEach(id => Quotidien.discover(id, 'manuel'))")
        ok('cinq cafés : carte commune « L\'habitué »', await pg.evaluate("!!V3.st().cards['c-habitue']"))
        # sac et territoires
        await pg.evaluate("UI.closeSheet(); document.querySelector('#tabbar [data-v=collection]').click()"); await pg.wait_for_timeout(300)
        await pg.click('[data-act="sac-tab"][data-v="adresses"]'); await pg.wait_for_timeout(300)
        ok('Sac → Adresses : collection par famille et liste des visités', await pg.locator('.qfam').count() == 13 and await pg.locator('[data-act="quot-open"]').count() >= 6)
        await pg.screenshot(path='q-sac.png')
        await pg.evaluate("document.querySelector('#tabbar [data-v=atlas]').click()"); await pg.click('#fab-list'); await pg.wait_for_timeout(300)
        ok('les six territoires : rang, progression, adresses, quêtes', await pg.locator('.terr').count() == 6 and 'passant' in (await pg.locator('.terr').first.inner_text()).lower(), await pg.locator('.terr').first.inner_text())
        await pg.screenshot(path='q-territoires.png')
        await pg.locator('.terr').nth(1).click(); await pg.wait_for_timeout(300)
        ok('fiche de territoire : rang, lieux, adresses, quêtes, secrets, donjon', await pg.locator('.terr-rank span').count() == 5 and await pg.locator('#sheet [data-act="open-adv"]').count() >= 1)
        await pg.screenshot(path='q-territoire.png', full_page=False)
