        ok('l\'invitation ne revient pas', 'Joue en plein écran' not in await pg.locator('body').inner_text())
        ok('rebond et sélection de texte désactivés', await pg.evaluate("getComputedStyle(document.body).userSelect === 'none' || getComputedStyle(document.body).webkitUserSelect === 'none'"))
        await pg.evaluate("document.querySelector('#tabbar [data-v=profil]').click()"); await pg.wait_for_timeout(300)
        ok('Héros : « Jouer en plein écran » toujours accessible', await pg.locator('[data-act="install"]').count() == 1)
        await ctx.close()
